// Lab_07_01.cpp — Частина 1: Хешування методом ланцюгів
#include <iostream>  // cout, cin — виведення і введення
#include <limits>    // numeric_limits — для очищення буфера вводу
#include "Hash.h" // наша бібліотека хеш-таблиць

// -------------------------------------------------------------
// Допоміжна функція: очищення буфера вводу після помилки
// Потрібна коли користувач вводить не число (наприклад "abc")
// -------------------------------------------------------------
static void clearInput() {
    std::cin.clear(); // скидаємо прапор помилки потоку cin
    // Ігноруємо всі символи до кінця рядка '\n'
    // numeric_limits<streamsize>::max() — дуже велике число (весь рядок)
    std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\n');
}

// -------------------------------------------------------------
// Допоміжна функція: безпечне зчитування цілого числа
// Виводить підказку prompt і чекає коректного числа
// Якщо введено не число — просить ввести ще раз
// -------------------------------------------------------------
static int readInt(const std::string& prompt) {
    int v; // сюди запишемо прочитане число
    while (true) { // нескінченний цикл поки не введуть правильно
        std::cout << prompt;      // виводимо підказку ("Введіть m: ")
        if (std::cin >> v)        // спробуємо зчитати число
            return v;             // успіх — повертаємо число
        // Якщо cin >> v не спрацювало (ввели не число):
        std::cout << "Некоректне введення, спробуйте ще раз.\n";
        clearInput(); // очищаємо буфер і пробуємо знову
    }
}

// -------------------------------------------------------------
// Головна функція програми
// -------------------------------------------------------------
int main() {
    // Вітальне повідомлення
    std::cout << "=== Лабораторна робота №7, Частина 1 ===\n";
    std::cout << "    Хешування методом ланцюгів\n\n";

    // Зчитуємо розмір таблиці m з клавіатури
    int m = readInt("Введіть розмір хеш-таблиці (m): ");

    // Перевірка: розмір має бути додатнім числом
    while (m <= 0) {
        std::cout << "Розмір повинен бути > 0.\n";
        m = readInt("Введіть розмір хеш-таблиці (m): ");
    }

    // Створюємо хеш-таблицю розміром m
    // ChainedHashCreate(m) повертає вектор з m порожніх списків
    ChainTable table = ChainedHashCreate(m);

    // Вибір хеш-функції на початку роботи
    std::cout << "\nОберіть хеш-функцію:\n";
    std::cout << "  0 - Метод ділення   h(k) = k mod m\n";
    std::cout << "  1 - Метод множення  h(k) = floor(m * frac(k*A))\n";
    int hashType = readInt("Ваш вибір: ");

    // Якщо ввели щось інше крім 0 або 1 — за замовчуванням метод ділення
    if (hashType != 0 && hashType != 1) hashType = 0;

    // Головний цикл меню
    int choice; // сюди зберігаємо вибір користувача
    do {
        // Виводимо меню
        std::cout << "\n--- МЕНЮ ---\n";
        std::cout << "  1. Вставити елемент\n";
        std::cout << "  2. Знайти елемент\n";
        std::cout << "  3. Видалити елемент\n";
        std::cout << "  4. Показати таблицю\n";
        std::cout << "  5. Змінити хеш-функцію\n";
        std::cout << "  0. Вихід\n";
        choice = readInt("Ваш вибір: ");

        // Обробляємо вибір через switch
        switch (choice) {

            case 1: { // ВСТАВКА
                int key = readInt("Введіть ключ для вставки: ");

                // Обчислюємо куди потрапить ключ (щоб показати користувачу)
                // Тернарний оператор: якщо hashType==0 → ділення, інакше → множення
                int idx = (hashType == 0) ? hashDivision(key, m)
                                          : hashMultiplication(key, m);

                // Вставляємо ключ у хеш-таблицю
                ChainedHashInsert(table, key, hashType);

                std::cout << "Ключ " << key << " вставлено у комірку ["
                          << idx << "]\n";
                break; // виходимо з switch
            }

            case 2: { // ПОШУК
                int key = readInt("Введіть ключ для пошуку: ");

                // ChainedHashSearch повертає true/false
                if (ChainedHashSearch(table, key, hashType))
                    std::cout << "Ключ " << key << " ЗНАЙДЕНО.\n";
                else
                    std::cout << "Ключ " << key << " НЕ ЗНАЙДЕНО.\n";
                break;
            }

            case 3: { // ВИДАЛЕННЯ
                int key = readInt("Введіть ключ для видалення: ");

                // ChainedHashDelete повертає true якщо видалено
                if (ChainedHashDelete(table, key, hashType))
                    std::cout << "Ключ " << key << " ВИДАЛЕНО.\n";
                else
                    std::cout << "Ключ " << key << " не знайдено.\n";
                break;
            }

            case 4: // ПОКАЗАТИ ТАБЛИЦЮ
                ChainedHashShow(table); // виводить всі ланцюги
                break;

            case 5: { // ЗМІНИТИ ХЕШ-ФУНКЦІЮ
                std::cout << "  0 - Метод ділення\n  1 - Метод множення\n";
                hashType = readInt("Ваш вибір: ");
                if (hashType != 0 && hashType != 1) hashType = 0;
                std::cout << "Хеш-функцію змінено.\n";
                break;
            }

            case 0: // ВИХІД
                std::cout << "До побачення!\n";
                break;

            default: // НЕВІДОМА КОМАНДА
                std::cout << "Невідома команда.\n";
        }

    } while (choice != 0); // повторюємо поки не обрали "0 - Вихід"

    return 0; // програма завершилась успішно
}