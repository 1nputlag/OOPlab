// Lab_06_01 — Алгоритм Краскала
// Побудова мінімального каркасу зваженого графа

#include <iostream>
#include <vector>
#include <algorithm>
#include "DSU.h"

// ─────────────────────────────────────────
// Структура ребра графа
// ─────────────────────────────────────────
struct Edge {
    int u, v;   // вершини, що утворюють ребро
    int weight; // вага ребра
};

// ─────────────────────────────────────────
// Сортування списку ребер за зростанням ваги
// Використовуємо сортування вставками (Insertion Sort)
// ─────────────────────────────────────────
void sort_edges(std::vector<Edge>& edges) {
    int n = edges.size();
    for (int i = 1; i < n; i++) {
        Edge key = edges[i];
        int j = i - 1;
        // Зсуваємо ребра з більшою вагою вправо
        while (j >= 0 && edges[j].weight > key.weight) {
            edges[j + 1] = edges[j];
            j--;
        }
        edges[j + 1] = key;
    }
}

// ─────────────────────────────────────────
// Алгоритм Краскала
// Повертає список ребер мінімального каркасу
// ─────────────────────────────────────────
std::vector<Edge> kruskal(int n, std::vector<Edge>& edges) {
    // Крок 1: сортуємо ребра за зростанням ваги
    sort_edges(edges);

    // Крок 2: ініціалізуємо DSU — кожна вершина у своїй множині
    DSU dsu;
    dsu.init(n);

    std::vector<Edge> mst;      // ребра мінімального каркасу
    int total_weight = 0;

    std::cout << "\n=== Протокол алгоритму Краскала ===\n";
    std::cout << "Ребро\t\tВага\tДобір у каркас\n";
    std::cout << "------------------------------------\n";

    // Крок 3: перебираємо ребра у порядку зростання ваги
    for (auto& e : edges) {
        std::cout << "(" << e.u + 1 << ", " << e.v + 1 << ")\t\t"
                  << e.weight << "\t";

        // set_union повертає true якщо вершини у РІЗНИХ множинах
        // (ребро не утворює цикл) → беремо в каркас
        if (dsu.set_union(e.u, e.v)) {
            mst.push_back(e);
            total_weight += e.weight;
            std::cout << "ТАК\n";

            // Каркас готовий, коли маємо n-1 ребер
            if ((int)mst.size() == n - 1) break;
        } else {
            std::cout << "НІ (цикл)\n";
        }
    }

    std::cout << "------------------------------------\n";
    std::cout << "Загальна вага каркасу: " << total_weight << "\n";

    return mst;
}

// ─────────────────────────────────────────
// Введення графа з клавіатури
// ─────────────────────────────────────────
int main() {
    int n, m;

    std::cout << "=== Алгоритм Краскала — Мінімальний каркас ===\n\n";
    std::cout << "Введіть кількість вершин: ";
    std::cin >> n;

    std::cout << "Введіть кількість ребер: ";
    std::cin >> m;

    std::vector<Edge> edges(m);

    std::cout << "\nВводьте ребра у форматі: v1 v2 вага\n";
    std::cout << "(нумерація вершин від 1 до " << n << ")\n\n";

    for (int i = 0; i < m; i++) {
        int u, v, w;
        std::cout << "Ребро " << i + 1 << ": ";
        std::cin >> u >> v >> w;

        // Перевірка коректності введення
        if (u < 1 || u > n || v < 1 || v > n) {
            std::cout << "Помилка: вершини мають бути від 1 до " << n << "\n";
            i--;
            continue;
        }
        if (w <= 0) {
            std::cout << "Помилка: вага повинна бути > 0\n";
            i--;
            continue;
        }

        edges[i] = {u - 1, v - 1, w}; // зберігаємо з 0-індексацією
    }

    std::cout << "\nГраф: " << n << " вершин, " << m << " ребер\n";

    std::vector<Edge> mst = kruskal(n, edges);

    std::cout << "\n=== Ребра мінімального каркасу ===\n";
    for (auto& e : mst) {
        std::cout << "  v" << e.u + 1 << " -- v" << e.v + 1
                  << "  (вага " << e.weight << ")\n";
    }

    return 0;
}