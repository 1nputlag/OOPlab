#pragma once
#include <vector>

// DSU (Disjoint Set Union) — система множин, що не перетинаються
// Кожна множина представлена у вигляді кореневого дерева.
// previous[v] — батько вершини v у цьому дереві.
// Корінь вказує сам на себе: previous[root] == root.

class DSU {
public:
    std::vector<int> previous; // масив предків

    // Створення (ініціалізація) системи DSU на n вершинах
    void init(int n);

    // Створити нову множину з одного елемента v
    // Вершина v стає коренем — вказує сама на себе
    void set_make(int v);

    // Знайти корінь дерева для вершини v (ідентифікатор множини)
    // Якщо v == previous[v], то v — корінь, повертаємо v
    // Інакше рекурсивно шукаємо корінь батька
    int set_find(int v);

    // Об'єднати дві множини, що містять вершини v1 та v2
    // Повертає true якщо об'єднання відбулося (були різні множини)
    // Повертає false якщо вже в одній множині (ребро утворило б цикл)
    bool set_union(int v1, int v2);
};
