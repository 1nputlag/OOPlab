// Lab_06_02 — Алгоритм Прима
// Побудова мінімального каркасу зваженого графа

#include <iostream>
#include <vector>
#include <climits>   // для INT_MAX (нескінченність)

// ─────────────────────────────────────────
// Алгоритм Прима
// n        — кількість вершин
// adj      — матриця суміжності (0 = ребра немає)
// start    — початкова вершина (0-індексація)
// ─────────────────────────────────────────
void prim(int n, const std::vector<std::vector<int>>& adj, int start) {

    // min_e[v]  — мінімальна вага ребра від v до вершин у каркасі
    //             INT_MAX означає "ще не знайдено з'єднання"
    std::vector<int> min_e(n, INT_MAX);

    // sel_e[v]  — яка вершина з каркасу з'єднана з v цим мінімальним ребром
    std::vector<int> sel_e(n, -1);

    // visited[v] — true, якщо вершина вже включена у каркас (у множині U)
    std::vector<bool> visited(n, false);

    // ─── Ініціалізація: починаємо з вершини start ───
    // Для стартової вершини вага = 0 (вона перша, без ребра)
    min_e[start] = 0;

    int total_weight = 0;

    std::cout << "\n=== Протокол алгоритму Прима (старт: v"
              << start + 1 << ") ===\n";
    std::cout << "Крок\tДодана вершина\tРебро\t\tВага\n";
    std::cout << "------------------------------------------------\n";

    for (int step = 0; step < n; step++) {

        // ─── Крок А: знайти незанесену вершину з мінімальним min_e ───
        // Це і є "найдешевше ребро між U і V\U"
        int u = -1;
        for (int v = 0; v < n; v++) {
            if (!visited[v] && (u == -1 || min_e[v] < min_e[u])) {
                u = v;
            }
        }

        // Позначаємо вершину u як включену в каркас
        visited[u] = true;

        // Виводимо крок
        std::cout << step + 1 << "\tv" << u + 1 << "\t\t";
        if (sel_e[u] == -1) {
            std::cout << "(стартова)\t-\n";
        } else {
            std::cout << "v" << sel_e[u] + 1 << " -- v" << u + 1
                      << "\t\t" << min_e[u] << "\n";
            total_weight += min_e[u];
        }

        // ─── Крок Б: оновити min_e та sel_e для сусідів u ───
        // Для кожного сусіда v вершини u (ще не в каркасі):
        // якщо вага ребра (u,v) менша за поточний min_e[v] → оновлюємо
        for (int v = 0; v < n; v++) {
            if (!visited[v] && adj[u][v] != 0) {
                if (adj[u][v] < min_e[v]) {
                    min_e[v] = adj[u][v]; // нова мінімальна вага до v
                    sel_e[v] = u;         // через вершину u
                }
            }
        }
    }

    std::cout << "------------------------------------------------\n";
    std::cout << "Загальна вага каркасу: " << total_weight << "\n";
}

// ─────────────────────────────────────────
// Введення графа з клавіатури
// ─────────────────────────────────────────
int main() {
    int n, m;

    std::cout << "=== Алгоритм Прима — Мінімальний каркас ===\n\n";
    std::cout << "Введіть кількість вершин: ";
    std::cin >> n;

    std::cout << "Введіть кількість ребер: ";
    std::cin >> m;

    // Матриця суміжності (0 = ребра немає)
    std::vector<std::vector<int>> adj(n, std::vector<int>(n, 0));

    std::cout << "\nВводьте ребра у форматі: v1 v2 вага\n";
    std::cout << "(нумерація вершин від 1 до " << n << ")\n\n";

    for (int i = 0; i < m; i++) {
        int u, v, w;
        std::cout << "Ребро " << i + 1 << ": ";
        std::cin >> u >> v >> w;

        // Перевірка коректності введення
        if (u < 1 || u > n || v < 1 || v > n) {
            std::cout << "Помилка: вершини мають бути від 1 до " << n << "\n";
            i--;
            continue;
        }
        if (w <= 0) {
            std::cout << "Помилка: вага повинна бути > 0\n";
            i--;
            continue;
        }

        // Незорієнтований граф — записуємо в обидва напрямки
        adj[u - 1][v - 1] = w;
        adj[v - 1][u - 1] = w;
    }

    int start;
    std::cout << "\nВведіть початкову вершину (від 1 до " << n << "): ";
    std::cin >> start;
    if (start < 1 || start > n) {
        std::cout << "Некоректна вершина, використовується v1\n";
        start = 1;
    }

    // Виводимо матрицю суміжності
    std::cout << "\nМатриця суміжності:\n    ";
    for (int i = 0; i < n; i++) std::cout << " v" << i + 1;
    std::cout << "\n";
    for (int i = 0; i < n; i++) {
        std::cout << "v" << i + 1 << "  ";
        for (int j = 0; j < n; j++) {
            std::cout << " " << (adj[i][j] < 10 ? " " : "") << adj[i][j];
        }
        std::cout << "\n";
    }

    prim(n, adj, start - 1); // передаємо з 0-індексацією

    return 0;
}